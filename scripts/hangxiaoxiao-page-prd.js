  function ensureTrigger(){
    let trigger=document.querySelector('[data-hxx-page-prd-trigger]');
    if(trigger)return trigger;
    trigger=document.createElement('button');
    trigger.type='button';
    trigger.className='hxx-page-prd-trigger';
    trigger.dataset.hxxPagePrdTrigger='';
    trigger.setAttribute('aria-controls','detailDrawer');
    trigger.setAttribute('aria-expanded','false');
    trigger.innerHTML='<span>页面</span><b>PRD</b>';
    document.body.appendChild(trigger);
    return trigger;
  }

  function syncTrigger(route=activeContext().route,subview=''){
    const key=pagePrdKey(route,subview),prd=HXX_PAGE_PRDS[key],trigger=ensureTrigger(),login=document.querySelector('#login');
    const loggedIn=!document.body.classList.contains('login-active')&&(!login||getComputedStyle(login).display==='none');
    trigger.hidden=!(loggedIn&&prd);
    trigger.dataset.hxxPagePrdKey=key;
    trigger.dataset.hxxPagePrdRoute=route;
    trigger.setAttribute('aria-label',prd?`查看${prd.title}`:'查看页面 PRD');
    if(trigger.hidden&&document.querySelector('#detailDrawer')?.dataset.hxxDrawerKind==='page-prd')window.closeDrawer?.();
  }

